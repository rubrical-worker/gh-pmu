// ============================================================================
// Named Operation Schema Validation (#886)
// ============================================================================
//
// Every GraphQL document this package sends is checked against the vendored
// public schema. This is the one check that can catch GitHub renaming or
// removing a field: hand-written mocks encode our assumptions about GitHub's
// responses, so they keep passing when the real schema moves. Zero API traffic
// — the capture transport answers every request itself.
//
// How the documents are obtained: most queries are shurcooL struct-based, so
// the document is generated by the library at call time rather than written
// literally, and constructQuery/constructMutation are unexported. So the
// document is captured, not requested — we point the client at a transport that
// records what was sent. Construction and POST both happen before the response
// is unmarshalled, which is why a stub response is enough to harvest a document.

// documentOperationName extracts the operation name from a GraphQL document,
// e.g. "query GetIssue($n:Int!)..." -> "GetIssue". Anonymous documents
// ("query { i0: issue(...) }") have none and yield "".
var documentOperationNamePattern = regexp.MustCompile(`^\s*(?:query|mutation)\s+([A-Za-z_][A-Za-z0-9_]*)`)

func documentOperationName(doc string) string {
	m := documentOperationNamePattern.FindStringSubmatch(doc)
	if m == nil {
		return ""
	}
	return m[1]
}

// capturingTransport records every GraphQL document that reaches the wire and
// answers it locally. Responses default to an empty data object; a per-operation
// response can be supplied for methods that only issue their second call if the
// first one came back with something usable.
type capturingTransport struct {
	mu        sync.Mutex
	docs      []string
	responses map[string]string
}

func (c *capturingTransport) RoundTrip(req *http.Request) (*http.Response, error) {
	var payload struct {
		Query string `json:"query"`
	}
	if req.Body != nil {
		body, err := io.ReadAll(req.Body)
		if err != nil {
			return nil, err
		}
		_ = json.Unmarshal(body, &payload)
	}

	if payload.Query != "" {
		c.mu.Lock()
		c.docs = append(c.docs, payload.Query)
		c.mu.Unlock()
	}

	body := `{"data":{}}`
	if r, ok := c.responses[documentOperationName(payload.Query)]; ok {
		body = r
	}
	return makeResp(200, body), nil
}

func (c *capturingTransport) captured() []string {
	c.mu.Lock()
	defer c.mu.Unlock()
	return append([]string(nil), c.docs...)
}

