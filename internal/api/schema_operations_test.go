// TestNamedOperations_CoverageIsComplete fails when an operation exists in the
// sources but no invocation drives it. Without this the validation test above
// silently shrinks as operations are added.
func TestNamedOperations_CoverageIsComplete(t *testing.T) {
	docs := captureNamedOperationDocuments(t)

	var uncovered []string
	for _, op := range sourceEnumeratedOperations(t) {
		if _, ok := docs[op]; !ok {
			uncovered = append(uncovered, op)
		}
	}

	if len(uncovered) > 0 {
		t.Errorf("%d operation(s) exist in source but no invocation drives them: %s\n"+
			"Add an entry to namedOperationInvocations (and a response to namedOperationResponses if the caller chains off a first result).",
			len(uncovered), strings.Join(uncovered, ", "))
	}
}
