// captureNamedOperationDocuments drives every invocation and returns the
// documents that reached the wire, keyed by operation name.
func captureNamedOperationDocuments(t *testing.T) map[string]string {
	t.Helper()

	transport := &capturingTransport{responses: namedOperationResponses()}
	SetTestTransport(transport)
	defer SetTestTransport(nil)
	SetTestAuthToken("test-token") // go-gh refuses to construct a client without one (CI lacks gh auth)
	defer SetTestAuthToken("")

	c, err := NewClient()
	if err != nil {
		t.Fatalf("NewClient failed: %v", err)
	}

	for _, invoke := range namedOperationInvocations() {
		invoke(c) // errors expected and ignored — only the sent document matters
	}

	docs := make(map[string]string)
	for _, d := range transport.captured() {
		if name := documentOperationName(d); name != "" {
			docs[name] = d
		}
	}
	return docs
}

// namedOperationResponses supplies canned responses for the operations whose
// callers chain a second request off the first one's result.
//
// Only one is needed. 36 of the 40 operations are harvested from an empty
// response, because the document is already on the wire by the time the reply is
// unmarshalled. The exceptions are the four label mutations: each resolves the
// label's node id first and bails with "label %q not found" on an empty result,
// so their own document never gets sent. Giving GetLabelID an id lets all four
// through.
func namedOperationResponses() map[string]string {
	return map[string]string{
		"GetLabelID": `{"data":{"repository":{"label":{"id":"LA_kwDOTestLabel"}}}}`,
	}
}

// knownInvalidOperations lists operations that do not validate against the
// vendored schema because the query itself is wrong, mapped to the issue
// tracking the fix.
//
// This is a quarantine, not an exemption. TestNamedOperations_KnownInvalidStillFail
// asserts each entry STILL fails, so fixing the underlying bug turns that test
// red until the entry is removed. A quarantine that silently rots is worse than
// no quarantine — it reads as coverage while providing none.
var knownInvalidOperations = map[string]string{}

// loadVendoredSchema parses the vendored schema once per test.
func loadVendoredSchema(t *testing.T) *ast.Schema {
	t.Helper()
	raw, err := os.ReadFile(vendoredSchemaPath)
	if err != nil {
		t.Fatalf("vendored schema not found at %s: %v", vendoredSchemaPath, err)
	}
	schema, gerr := gqlparser.LoadSchema(&ast.Source{Name: "github.docs", Input: string(raw)})
	if gerr != nil {
		t.Fatalf("vendored schema failed to parse: %v", gerr)
	}
	return schema
}

// sourceEnumeratedOperations lists the operation names this package sends, read
// from the production sources. Test files are excluded deliberately: they define
// operations of their own (Test, Viewer in client_test.go) that GitHub's schema
// knows nothing about.
func sourceEnumeratedOperations(t *testing.T) []string {
	t.Helper()

	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatalf("cannot read package dir: %v", err)
	}

	pattern := regexp.MustCompile(`gql\.(?:Query|Mutate)\("([A-Za-z]+)"`)
	seen := make(map[string]bool)
	for _, e := range entries {
		name := e.Name()
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		src, err := os.ReadFile(name)
		if err != nil {
			t.Fatalf("cannot read %s: %v", name, err)
		}
		for _, m := range pattern.FindAllStringSubmatch(string(src), -1) {
			seen[m[1]] = true
		}
	}

	ops := make([]string, 0, len(seen))
	for op := range seen {
		ops = append(ops, op)
	}
	sort.Strings(ops)
	return ops
}

// TestNamedOperations_ValidateAgainstVendoredSchema is the check that catches an
// upstream field rename or removal.
func TestNamedOperations_ValidateAgainstVendoredSchema(t *testing.T) {
	schema := loadVendoredSchema(t)
	docs := captureNamedOperationDocuments(t)

	if len(docs) == 0 {
		t.Fatal("no documents captured — the capture transport is not wired up")
	}

	names := make([]string, 0, len(docs))
	for name := range docs {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		if _, quarantined := knownInvalidOperations[name]; quarantined {
			continue // asserted separately by TestNamedOperations_KnownInvalidStillFail
		}
		t.Run(name, func(t *testing.T) {
			if _, errs := gqlparser.LoadQueryWithRules(schema, docs[name], nil); len(errs) > 0 {
				for _, e := range errs {
					t.Errorf("%s does not validate against the vendored schema: %s", name, e.Message)
				}
				t.Logf("document: %s", docs[name])
			}
		})
	}
}

// TestNamedOperations_KnownInvalidStillFail keeps the quarantine honest. Every
// entry must still be broken; the moment one starts validating, the entry is
// stale and has to go, or the operation silently drops out of coverage.
func TestNamedOperations_KnownInvalidStillFail(t *testing.T) {
	schema := loadVendoredSchema(t)
	docs := captureNamedOperationDocuments(t)

	for name, reason := range knownInvalidOperations {
		doc, ok := docs[name]
		if !ok {
			t.Errorf("%s is quarantined (%s) but no invocation drives it — remove the entry or add the invocation",
				name, reason)
			continue
		}
		if _, errs := gqlparser.LoadQueryWithRules(schema, doc, nil); len(errs) == 0 {
			t.Errorf("%s is quarantined (%s) but now validates cleanly — remove it from knownInvalidOperations",
				name, reason)
		}
	}
}

