// TestRawDocuments_ValidateAgainstVendoredSchema checks the hand-assembled
// documents. Each builder is driven separately so a failure names the builder
// rather than a line of generated GraphQL.
func TestRawDocuments_ValidateAgainstVendoredSchema(t *testing.T) {
	schema := loadVendoredSchema(t)

	for _, tc := range rawDocumentInvocations() {
		t.Run(tc.label, func(t *testing.T) {
			transport := &capturingTransport{responses: namedOperationResponses()}
			SetTestTransport(transport)
			defer SetTestTransport(nil)
			SetTestAuthToken("test-token") // go-gh refuses to construct a client without one (CI lacks gh auth)
			defer SetTestAuthToken("")

			c, err := NewClient()
			if err != nil {
				t.Fatalf("NewClient failed: %v", err)
			}

			tc.invoke(c) // errors expected and ignored — only the sent document matters

			docs := transport.captured()
			if len(docs) == 0 {
				t.Fatalf("%s sent no document — the invocation does not reach the send", tc.label)
			}

			for _, doc := range docs {
				if _, errs := gqlparser.LoadQueryWithRules(schema, doc, nil); len(errs) > 0 {
					for _, e := range errs {
						t.Errorf("%s does not validate against the vendored schema: %s", tc.label, e.Message)
					}
					t.Logf("document: %s", doc)
				}
			}
		})
	}
}

// TestSchemaValidation_NoLiveAPITraffic asserts the claim the rest of this file
// depends on: nothing here talks to GitHub. Live API calls are barred outright
// (#876 — burst traffic from CI tripped abuse detection and locked the account),
// so "we use a mock" has to be checked rather than believed.
func TestSchemaValidation_NoLiveAPITraffic(t *testing.T) {
	transport := &capturingTransport{responses: namedOperationResponses()}
	SetTestTransport(transport)
	defer SetTestTransport(nil)
	SetTestAuthToken("test-token") // go-gh refuses to construct a client without one (CI lacks gh auth)
	defer SetTestAuthToken("")

	c, err := NewClient()
	if err != nil {
		t.Fatalf("NewClient failed: %v", err)
	}

	// A sentinel only the capture transport can produce: no live endpoint would
	// return this id for label "bug" on owner/repo. If SetTestTransport failed to
	// take effect, this call would reach GitHub and could not return it.
	got, err := c.getLabelID("owner", "repo", "bug")
	if err != nil {
		t.Fatalf("getLabelID returned an error, so the transport did not answer it: %v", err)
	}
	if got != "LA_kwDOTestLabel" {
		t.Errorf("getLabelID returned %q, not the canned fixture id — the response did not come from the capture transport", got)
	}

	if len(transport.captured()) == 0 {
		t.Fatal("capture transport received no requests — traffic escaped the test transport")
	}

	// The schema oracle is a file on disk, not a network fetch.
	if _, err := os.Stat(vendoredSchemaPath); err != nil {
		t.Errorf("validation must run against the vendored file, but it is not readable: %v", err)
	}
}

// ============================================================================
// Fail-Proof (#886)
// ============================================================================
//
// A validator that cannot fail is worse than no validator: it reports safety it
// is not providing. These tests take a real captured document, inject a field
// GitHub does not have, and require the rejection — with a control asserting the
// same document passes untouched, so the failure is provably caused by the
// injection rather than by a document that was already broken.

const bogusField = "bogusFieldThatDoesNotExist"

// validationErrors returns the validation messages for doc against schema, or
// nil when it validates cleanly.
func validationErrors(schema *ast.Schema, doc string) []string {
	_, gerrs := gqlparser.LoadQueryWithRules(schema, doc, nil)
	var out []string
	for _, e := range gerrs {
		out = append(out, e.Message)
	}
	return out
}

// injectBogusField splices a nonexistent field into a document's first
// selection set after marker.
func injectBogusField(t *testing.T, doc, marker string) string {
	t.Helper()
	i := strings.Index(doc, marker)
	if i < 0 {
		t.Fatalf("marker %q not found in document — the query shape changed and this test needs updating.\ndocument: %s",
			marker, doc)
	}
	cut := i + len(marker)
	return doc[:cut] + bogusField + "," + doc[cut:]
}

func TestFailProof_BogusFieldInNamedOperationIsRejected(t *testing.T) {
	schema := loadVendoredSchema(t)
	docs := captureNamedOperationDocuments(t)

	doc, ok := docs["GetIssue"]
	if !ok {
		t.Fatal("GetIssue was not captured — cannot prove the validator fails")
	}

	// Control: the real document must pass, or the negative below proves nothing.
	if errs := validationErrors(schema, doc); len(errs) > 0 {
		t.Fatalf("control failed: the real GetIssue document does not validate: %v", errs)
	}

	mutated := injectBogusField(t, doc, "issue(number: $number){")

	errs := validationErrors(schema, mutated)
	if len(errs) == 0 {
		t.Fatalf("injecting %q into GetIssue did not fail validation — the validator is not checking fields.\ndocument: %s",
			bogusField, mutated)
	}
	if !strings.Contains(strings.Join(errs, " "), bogusField) {
		t.Errorf("validation failed, but not because of the injected field. Errors: %v", errs)
	}
}

